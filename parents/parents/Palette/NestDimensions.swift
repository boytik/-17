

import SwiftUI


enum NestDimensions {

    /// Standard corner radius for cards.
    static let cradleCorner: CGFloat        = 16

    /// Small corner radius for buttons, badges.
    static let pebbleCorner: CGFloat        = 10

    /// Large corner radius for modals, sheets.
    static let blanketCorner: CGFloat       = 24

    /// Minimum touch target (HIG 44pt).
    static let touchCradle: CGFloat         = 44

    /// Standard horizontal padding.
    static let nestPadding: CGFloat         = 16

    /// Inner card padding.
    static let cradlePadding: CGFloat       = 14

    /// Space between cards.
    static let blockGap: CGFloat            = 12

    /// Elevated card shadow radius.
    static let liftedShadow: CGFloat        = 12
}
